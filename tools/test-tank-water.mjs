import assert from 'node:assert/strict';
import { advanceTankFlood, tankFloodHeight, TANK_EVACUATION_TIME } from '../src/game/vehicleWater.ts';
import { getMap } from '../src/game/maps.ts';
const w = getMap('prigorod').water;
const args = [w, 't72', [-48, 0, 50], 2.2, 0.35];
const step = (prev, dt = 1 / 60) => advanceTankFlood(...args, false, prev, dt);
assert.equal(advanceTankFlood(...args, true, null, 1), null, 'мост не затапливает танк');
assert.equal(advanceTankFlood(w, 't72', [-48, 0, 130], 2.2, 0.35, false, null, 1), null, 'брод не затапливает танк');
assert.equal(advanceTankFlood(w, 'btr80', [-48, 0, 50], 2.4, 0.6, false, null, 1), null, 'БТР не затапливается');
assert.equal(advanceTankFlood(w, 't72', [0, 0, 0], 2.2, 0.35, false, null, 1), null, 'на суше не затапливается');
let flood = step(null, 0);
for (let i = 0; i < 9 * 60; i++) flood = step(flood);
assert.ok(!flood.sunk && Math.abs(flood.elapsed - 9) < 1e-6, 'до конца 10 секунд можно выйти');
assert.ok(tankFloodHeight(flood) < flood.startY, 'танк погружается');
assert.equal(advanceTankFlood(w, 't72', [0, 0, 0], 2.2, 0.35, false, flood, 1), null, 'при выезде на сушу затопление сбрасывается');
flood = step(flood, 1.001);
assert.equal(flood.sunk, true);
assert.equal(flood.elapsed, TANK_EVACUATION_TIME);
assert.equal(tankFloodHeight(flood), flood.bottomY);
assert.equal(advanceTankFlood(w, 't72', [0, 0, 0], 2.2, 0.35, false, flood, 1).sunk, true, 'затонувший танк не восстанавливается');
console.log('ИТОГ: OK — затопление танка, 10 секунд, мост и брод');
