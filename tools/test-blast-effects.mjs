import assert from 'node:assert/strict';
import * as THREE from 'three';
import { planBlast, blastDamage } from '../src/game/blastEffects.ts';
import { Bots } from '../src/game/bots.ts';
const water = { level: 0, x0: -50, x1: 50, z0: -50, z1: 50, depth: 5 };
const base = { radius: 10, damage: 100, craterRadius: 1, craterStrength: 60, propRadius: 2, propStrength: 140, maxVoxels: 8 };
const wetPos = [0, -1, 0];
const wet = planBlast(water, wetPos, base), air = planBlast(water, [0, 1, 0], base);
assert.equal(wet.underwater, true);
assert.equal(wet.radius, 16); assert.equal(wet.damage, 180);
assert.equal(wet.craterRadius, 1.6); assert.equal(wet.craterStrength, 108);
assert.equal(wet.propRadius, 3.2); assert.equal(wet.propStrength, 252);
assert.equal(wet.maxVoxels, 8, 'сохранён бюджет разрушений');
assert.equal(air.radius, 10); assert.equal(air.damage, 100);
assert.equal(planBlast(water, [80, -1, 0], base).underwater, false);
assert.equal(blastDamage(10, 10, 100), 0);
assert.equal(blastDamage(5, 10, 100), 50);
assert.ok(blastDamage(11, wet.radius, wet.damage) > 0 && blastDamage(11, air.radius, air.damage) === 0);
const impulses = [], death = [];
const bots = new Bots(new THREE.Scene(), {}, { post: msg => impulses.push(msg) });
bots.onDeath = b => death.push(b.id);
const make = (id, x, dead = false) => {
  const object = new THREE.Group(); object.position.set(x, -1.9, 0);
  return { id, hp: 100, maxHp: 100, object, bodyId: id, height: 1.8, dead, side: 1 };
};
const near = make(1, 1), edge = make(2, 11), outside = make(3, 17), alreadyDead = make(4, 1, true);
bots.list = [near, edge, outside, alreadyDead];
assert.equal(bots.blast(wetPos, wet.radius, wet.damage), 1);
assert.equal(near.dead, true);
assert.ok(edge.hp > 40 && edge.hp < 45, `живой бот на дистанции получил урон: ${edge.hp}`);
assert.equal(outside.hp, 100); assert.equal(alreadyDead.hp, 100);
assert.deepEqual(death, [1]); assert.equal(impulses.length, 1, 'реакция смерти вызывается один раз');
console.log('ИТОГ: OK — единые параметры ударной волны, здания и живые боты');
