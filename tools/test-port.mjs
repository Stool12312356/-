import assert from 'node:assert/strict';
import * as THREE from 'three';
import { getMap } from '../src/game/maps.ts';
import { buildGround } from '../src/game/ground.ts';
import { heightAt, setTerrainWater, setWorldSize } from '../src/game/terrain.ts';
import { spawnDressing } from '../src/game/dressing.ts';
import { WaterSurface } from '../src/game/water.ts';
import { VEHICLE_SPAWNS } from '../src/game/vehicles.ts';
const port = getMap('port');
assert.equal(port.id, 'port');
assert.equal(port.size, 600);
assert.ok(port.water && port.water.depth >= 3);
assert.ok(port.dressing.filter(x => x.kind === 'crane').length >= 2);
assert.ok(port.dressing.filter(x => x.kind === 'container').length >= 4);
assert.ok(port.specials.filter(x => x.label?.includes('Склад')).length >= 2);
assert.ok(VEHICLE_SPAWNS.port.length >= 2);
const bodies = [], scene = new THREE.Scene(), phys = { add: b => bodies.push(b) };
const waterSurface = new WaterSurface(scene, port.water);
assert.ok(waterSurface.mesh.geometry.attributes.position.count > 4, 'волны используют сетку, а не четыре вершины');
assert.ok(waterSurface.mesh.material.vertexShader.includes('modelViewMatrix * vec4(p, 1.0)'), 'деформация волн попадает в экранные координаты');
const t = buildGround(scene, phys, port.size, port.water);
assert.equal(heightAt(0, 160), -5, 'дно залива ниже поверхности');
assert.equal(heightAt(0, 80), 0, 'сухая набережная');
const n = Math.sqrt(t.verts.length / 3), i = Math.round((0 + 300) / 2.5), j = Math.round((160 + 300) / 2.5);
assert.equal(t.verts[(j * n + i) * 3 + 1], -5, 'коллизия и визуальный террейн имеют одно дно');
assert.equal(bodies[0].shapes[0].verts, t.verts);
spawnDressing(scene, phys, port.dressing);
assert.equal(bodies.filter(b => b.surface === 'metal' && b.shapes[0].he?.[1] === 10).length, 4, 'у каждого крана две опоры, не сплошная стена');
assert.ok(port.points.every(p => p.pos[2] < port.water.z0));
setTerrainWater(); setWorldSize(400);
assert.equal(heightAt(0, 160), 0, 'водоём не протекает на другую карту');
console.log('ИТОГ: OK — порт, рельеф залива и коллайдеры');
